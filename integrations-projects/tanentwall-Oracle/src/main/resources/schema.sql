-- ═══ Oracle Schema ═══
-- No DROP (relies on spring.sql.init.continue-on-error for idempotency)
-- For clean reset: docker compose down -v

CREATE TABLE categories (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    slug VARCHAR2(100),
    tenant_id VARCHAR2(50) NOT NULL
);
CREATE INDEX idx_cat_tenant ON categories(tenant_id);

CREATE TABLE suppliers (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    name VARCHAR2(150) NOT NULL,
    email VARCHAR2(150),
    phone VARCHAR2(50),
    tenant_id VARCHAR2(50) NOT NULL
);
CREATE INDEX idx_sup_tenant ON suppliers(tenant_id);

CREATE TABLE products (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    name VARCHAR2(200) NOT NULL,
    sku VARCHAR2(100) NOT NULL,
    price NUMBER(12,2) NOT NULL,
    stock_quantity NUMBER(10) NOT NULL,
    category_id NUMBER,
    supplier_id NUMBER,
    tenant_id VARCHAR2(50) NOT NULL,
    CONSTRAINT fk_prod_cat FOREIGN KEY (category_id) REFERENCES categories(id),
    CONSTRAINT fk_prod_sup FOREIGN KEY (supplier_id) REFERENCES suppliers(id)
);
CREATE INDEX idx_prod_tenant ON products(tenant_id);
CREATE INDEX idx_prod_category ON products(category_id);
CREATE INDEX idx_prod_supplier ON products(supplier_id);